package analysis

import (
	"context"
	"errors"
	"fmt"
	"sort"
	"strings"

	"bonanza.build/pkg/label"
	model_core "bonanza.build/pkg/model/core"
	"bonanza.build/pkg/model/core/btree"
	"bonanza.build/pkg/model/evaluation"
	model_analysis_pb "bonanza.build/pkg/proto/model/analysis"
	model_core_pb "bonanza.build/pkg/proto/model/core"
)

func (baseComputer[TReference, TMetadata]) ComputeCanonicalRepoNameValue(ctx context.Context, key *model_analysis_pb.CanonicalRepoName_Key, e CanonicalRepoNameEnvironment[TReference, TMetadata]) (PatchedCanonicalRepoNameValue[TMetadata], error) {
	fromCanonicalRepo, err := label.NewCanonicalRepo(key.GetFromCanonicalRepo())
	if err != nil {
		return PatchedCanonicalRepoNameValue[TMetadata]{}, fmt.Errorf("invalid canonical repo: %w", err)
	}

	toApparentRepo := key.GetToApparentRepo()
	if moduleExtension, _, ok := fromCanonicalRepo.GetModuleExtension(); ok {
		// Repos that were generated by the same module
		// extension are capable of accessing each other using
		// their short names. The root module may also override
		// these repos, or inject additional ones.
		analysisReaders, gotAnalysisReaders := getAnalysisReaders(e)
		moduleExtensionRepoMappingValue := e.GetModuleExtensionRepoMappingValue(model_analysis_pb.ModuleExtensionRepoMapping_Key_builder{
			ModuleExtension: moduleExtension.String(),
		}.Build())
		if !gotAnalysisReaders || !moduleExtensionRepoMappingValue.IsSet() {
			return PatchedCanonicalRepoNameValue[TMetadata]{}, evaluation.ErrMissingDependency
		}
		mapping, err := btree.Find(
			ctx,
			analysisReaders.ModuleExtensionRepoMappingValueMapping,
			model_core.Nested(moduleExtensionRepoMappingValue, moduleExtensionRepoMappingValue.Message.GetMappings()),
			func(entry model_core.Message[*model_analysis_pb.ModuleExtensionRepoMapping_Value_Mapping, TReference]) (int, *model_core_pb.DecodableReference) {
				switch entry.Message.WhichLevel() {
				case model_analysis_pb.ModuleExtensionRepoMapping_Value_Mapping_Leaf_case:
					return strings.Compare(toApparentRepo, entry.Message.GetLeaf().GetFromApparentRepo()), nil
				case model_analysis_pb.ModuleExtensionRepoMapping_Value_Mapping_Parent_case:
					return strings.Compare(toApparentRepo, entry.Message.GetParent().GetFirstFromApparentRepo()), entry.Message.GetParent().GetReference()
				default:
					return 0, nil
				}
			},
		)
		if err != nil {
			return PatchedCanonicalRepoNameValue[TMetadata]{}, err
		}
		if mapping.IsSet() {
			leaf := mapping.Message.GetLeaf()
			if leaf == nil {
				return PatchedCanonicalRepoNameValue[TMetadata]{}, errors.New("repo mapping has an unknown level type")
			}
			return model_core.NewSimplePatchedMessage[TMetadata](model_analysis_pb.CanonicalRepoName_Value_builder{
				ToCanonicalRepo: getRepoMappingCanonicalRepo(
					leaf,
					getModuleExtensionRepoMappingDefault(moduleExtension, toApparentRepo),
				),
			}.Build()), nil
		}
	}

	// Consider modules and repos declared in MODULE.bazel.
	moduleRepoMappingValue := e.GetModuleRepoMappingValue(model_analysis_pb.ModuleRepoMapping_Key_builder{
		ModuleInstance: fromCanonicalRepo.GetModuleInstance().String(),
	}.Build())
	if !moduleRepoMappingValue.IsSet() {
		return PatchedCanonicalRepoNameValue[TMetadata]{}, evaluation.ErrMissingDependency
	}
	mappings := moduleRepoMappingValue.Message.GetMappings()
	if mappingIndex, ok := sort.Find(
		len(mappings),
		func(i int) int { return strings.Compare(toApparentRepo, mappings[i].GetFromApparentRepo()) },
	); ok {
		return model_core.NewSimplePatchedMessage[TMetadata](model_analysis_pb.CanonicalRepoName_Value_builder{
			ToCanonicalRepo: getRepoMappingCanonicalRepo(
				mappings[mappingIndex],
				getModuleRepoMappingDefault(toApparentRepo),
			),
		}.Build()), nil
	}

	// Unknown repo.
	return model_core.NewSimplePatchedMessage[TMetadata](&model_analysis_pb.CanonicalRepoName_Value{}), nil
}

type labelResolverEnvironment[TReference any] interface {
	CanonicalRepoNameValueGetter[TReference]
	RootModuleValueGetter[TReference]
}

// labelResolver is an implementation of label.Resolver that is built on
// top of the CanonicalRepoName and RootModule analysis functions. It is
// provided to make resolution of apparent labels and target patterns
// to their canonical counterparts work.
type labelResolver[TReference any] struct {
	environment labelResolverEnvironment[TReference]
}

func newLabelResolver[TReference any](e labelResolverEnvironment[TReference]) label.Resolver {
	return &labelResolver[TReference]{
		environment: e,
	}
}

func (r *labelResolver[TReference]) GetCanonicalRepo(fromCanonicalRepo label.CanonicalRepo, toApparentRepo label.ApparentRepo) (*label.CanonicalRepo, error) {
	v := r.environment.GetCanonicalRepoNameValue(model_analysis_pb.CanonicalRepoName_Key_builder{
		FromCanonicalRepo: fromCanonicalRepo.String(),
		ToApparentRepo:    toApparentRepo.String(),
	}.Build())
	if !v.IsSet() {
		return nil, evaluation.ErrMissingDependency
	}
	if v.Message.GetToCanonicalRepo() == "" {
		return nil, nil
	}
	toCanonicalRepo, err := label.NewCanonicalRepo(v.Message.GetToCanonicalRepo())
	if err != nil {
		return nil, fmt.Errorf("invalid canonical repo name %#v: %w", v.Message.GetToCanonicalRepo(), err)
	}
	return &toCanonicalRepo, nil
}

func (r *labelResolver[TReference]) GetRootModule() (label.Module, error) {
	v := r.environment.GetRootModuleValue(&model_analysis_pb.RootModule_Key{})
	var bad label.Module
	if !v.IsSet() {
		return bad, evaluation.ErrMissingDependency
	}
	rootModule, err := label.NewModule(v.Message.GetRootModuleName())
	if err != nil {
		return bad, fmt.Errorf("invalid root module name %#v: %w", v.Message.GetRootModuleName(), err)
	}
	return rootModule, nil
}
