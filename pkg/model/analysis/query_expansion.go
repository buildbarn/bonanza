// labelSet is a set of canonical labels of targets, as yielded by the
// evaluation of a query expression.
type labelSet map[label.CanonicalLabel]struct{}

func newLabelSet(labels []label.CanonicalLabel) labelSet {
	s := make(labelSet, len(labels))
	for _, l := range labels {
		s[l] = struct{}{}
	}
	return s
}

// sorted returns the labels contained in the set, in the order defined
// by label.CanonicalLabel.Compare().
func (s labelSet) sorted() []label.CanonicalLabel {
	return slices.SortedFunc(maps.Keys(s), label.CanonicalLabel.Compare)
}

// canonicalizeResolvedQueryLabel converts a label that is stored in a
// target definition (e.g., as part of an attribute value) to a canonical
// label. This fails if the label refers to a repo that does not exist.
func canonicalizeResolvedQueryLabel(resolvedLabel label.ResolvedLabel) (label.CanonicalLabel, error) {
	canonicalLabel, err := resolvedLabel.AsCanonical()
	if err != nil {
		return label.CanonicalLabel{}, fmt.Errorf("invalid label %#v: %w", resolvedLabel.String(), err)
	}
	return canonicalLabel, nil
}

// canonicalizeQueryLabel is identical to
// canonicalizeResolvedQueryLabel(), except that it accepts the label as
// a string.
func canonicalizeQueryLabel(s string) (label.CanonicalLabel, error) {
	resolvedLabel, err := label.NewResolvedLabel(s)
	if err != nil {
		return label.CanonicalLabel{}, fmt.Errorf("invalid label %#v: %w", s, err)
	}
	return canonicalizeResolvedQueryLabel(resolvedLabel)
}

// queryAttr contains the value of an attribute of a rule target. As
// target definitions are not configured, the value of the attribute
// may depend on select() expressions. All possible values are
// returned.
type queryAttr[TReference any] struct {
	name string
	// Whether the attribute is of type output or output_list. These
	// attributes contain labels of files that are generated by the
	// rule target, as opposed to dependencies.
	isOutput bool
	// Whether the value of the attribute was provided explicitly,
	// as opposed to being a default value.
	isExplicit bool
	// The value of the attribute, as a sequence of parts that need
	// to be concatenated. Each part may have multiple alternative
	// values, due to the use of select().
	parts [][]model_core.Message[*model_starlark_pb.Value, TReference]
	// Labels of the conditions of select() expressions used by the
	// attribute.
	conditionLabels []string
}

// appendSelectGroup adds the alternative values of a select()
// expression to an attribute value.
func (a *queryAttr[TReference]) appendSelectGroup(selectGroup model_core.Message[*model_starlark_pb.Select_Group, TReference]) {
	var alternatives []model_core.Message[*model_starlark_pb.Value, TReference]
	for _, condition := range selectGroup.Message.Conditions {
		a.conditionLabels = append(a.conditionLabels, condition.ConditionIdentifier)
		alternatives = append(alternatives, model_core.Nested(selectGroup, condition.Value))
	}
	if noMatch, ok := selectGroup.Message.NoMatch.(*model_starlark_pb.Select_Group_NoMatchValue); ok {
		alternatives = append(alternatives, model_core.Nested(selectGroup, noMatch.NoMatchValue))
	}
	a.parts = append(a.parts, alternatives)
}

func newQueryLabelListValue[TReference any](labels []string) model_core.Message[*model_starlark_pb.Value, TReference] {
	elements := make([]*model_starlark_pb.List_Element, 0, len(labels))
	for _, l := range labels {
		elements = append(elements, &model_starlark_pb.List_Element{
			Level: &model_starlark_pb.List_Element_Leaf{
				Leaf: &model_starlark_pb.Value{
					Kind: &model_starlark_pb.Value_Label{Label: l},
				},
			},
		})
	}
	return model_core.NewSimpleMessage[TReference](&model_starlark_pb.Value{
		Kind: &model_starlark_pb.Value_List{
			List: &model_starlark_pb.List{Elements: elements},
		},
	})
}

// queryRuleTarget contains properties of a rule target that are needed
// to evaluate query expressions.
type queryRuleTarget[TReference any] struct {
	// Attributes of the rule target, including ones that are
	// common to all rules (e.g., "name" and "tags").
	attrs []queryAttr[TReference]
}

func (t *queryRuleTarget[TReference]) getAttr(name string) (*queryAttr[TReference], bool) {
	for i := range t.attrs {
		if t.attrs[i].name == name {
			return &t.attrs[i], true
		}
	}
	return nil, false
}

type getQueryRuleTargetEnvironment[TReference any] interface {
	GetCompiledBzlFileGlobalValue(*model_analysis_pb.CompiledBzlFileGlobal_Key) model_core.Message[*model_analysis_pb.CompiledBzlFileGlobal_Value, TReference]
}

// getQueryRuleDefinition obtains the definition of the rule used by a
// rule target.
func getQueryRuleDefinition[TReference any](
	e getQueryRuleTargetEnvironment[TReference],
	ruleIdentifier label.CanonicalStarlarkIdentifier,
) (model_core.Message[*model_starlark_pb.Rule_Definition, TReference], error) {
	ruleValue := e.GetCompiledBzlFileGlobalValue(&model_analysis_pb.CompiledBzlFileGlobal_Key{
		Identifier: ruleIdentifier.String(),
	})
	if !ruleValue.IsSet() {
		return model_core.Message[*model_starlark_pb.Rule_Definition, TReference]{}, evaluation.ErrMissingDependency
	}
	v, ok := ruleValue.Message.Global.GetKind().(*model_starlark_pb.Value_Rule)
	if !ok {
		return model_core.Message[*model_starlark_pb.Rule_Definition, TReference]{}, fmt.Errorf("%#v is not a rule", ruleIdentifier.String())
	}
	d, ok := v.Rule.Kind.(*model_starlark_pb.Rule_Definition_)
	if !ok {
		return model_core.Message[*model_starlark_pb.Rule_Definition, TReference]{}, fmt.Errorf("%#v is not a rule definition", ruleIdentifier.String())
	}
	return model_core.Nested(ruleValue, d.Definition), nil
}

// getQueryRuleTarget obtains the attribute values of a rule target,
// using the definition of the rule to determine which attributes are
// present and what their default values are.
func getQueryRuleTarget[TReference any](
	e getQueryRuleTargetEnvironment[TReference],
	targetLabel label.CanonicalLabel,
	ruleTarget model_core.Message[*model_starlark_pb.RuleTarget, TReference],
) (*queryRuleTarget[TReference], error) {
	ruleIdentifier, err := label.NewCanonicalStarlarkIdentifier(ruleTarget.Message.RuleIdentifier)
	if err != nil {
		return nil, fmt.Errorf("invalid rule identifier %#v: %w", ruleTarget.Message.RuleIdentifier, err)
	}
	ruleDefinition, err := getQueryRuleDefinition(e, ruleIdentifier)
	if err != nil {
		return nil, err
	}

	t := &queryRuleTarget[TReference]{}

	// Attributes that are common to all rules.
	tags := make([]*model_starlark_pb.List_Element, 0, len(ruleTarget.Message.Tags))
	for _, tag := range ruleTarget.Message.Tags {
		tags = append(tags, &model_starlark_pb.List_Element{
			Level: &model_starlark_pb.List_Element_Leaf{
				Leaf: &model_starlark_pb.Value{
					Kind: &model_starlark_pb.Value_Str{Str: tag},
				},
			},
		})
	}
	t.attrs = append(
		t.attrs,
		queryAttr[TReference]{
			name:       "exec_compatible_with",
			isExplicit: true,
			parts: [][]model_core.Message[*model_starlark_pb.Value, TReference]{{
				newQueryLabelListValue[TReference](ruleTarget.Message.ExecCompatibleWith),
			}},
		},
		queryAttr[TReference]{
			name: "name",
			parts: [][]model_core.Message[*model_starlark_pb.Value, TReference]{{
				model_core.NewSimpleMessage[TReference](&model_starlark_pb.Value{
					Kind: &model_starlark_pb.Value_Str{Str: targetLabel.GetTargetName().String()},
				}),
			}},
			isExplicit: true,
		},
		queryAttr[TReference]{
			name: "package_metadata",
			parts: [][]model_core.Message[*model_starlark_pb.Value, TReference]{{
				newQueryLabelListValue[TReference](ruleTarget.Message.InheritableAttrs.GetPackageMetadata()),
			}},
		},
		queryAttr[TReference]{
			name:       "tags",
			isExplicit: true,
			parts: [][]model_core.Message[*model_starlark_pb.Value, TReference]{{
				model_core.NewSimpleMessage[TReference](&model_starlark_pb.Value{
					Kind: &model_starlark_pb.Value_List{
						List: &model_starlark_pb.List{Elements: tags},
					},
				}),
			}},
		},
		queryAttr[TReference]{
			name:       "testonly",
			isExplicit: true,
			parts: [][]model_core.Message[*model_starlark_pb.Value, TReference]{{
				model_core.NewSimpleMessage[TReference](&model_starlark_pb.Value{
					Kind: &model_starlark_pb.Value_Bool{Bool: ruleTarget.Message.InheritableAttrs.GetTestonly()},
				}),
			}},
		},
	)
	targetCompatibleWith := queryAttr[TReference]{
		name:       "target_compatible_with",
		isExplicit: true,
	}
	for _, selectGroup := range ruleTarget.Message.TargetCompatibleWith {
		targetCompatibleWith.appendSelectGroup(model_core.Nested(ruleTarget, selectGroup))
	}
	t.attrs = append(t.attrs, targetCompatibleWith)
	if buildSettingDefault := ruleTarget.Message.BuildSettingDefault; buildSettingDefault != nil {
		t.attrs = append(t.attrs, queryAttr[TReference]{
			name:       "build_setting_default",
			isExplicit: true,
			parts: [][]model_core.Message[*model_starlark_pb.Value, TReference]{{
				model_core.Nested(ruleTarget, buildSettingDefault),
			}},
		})
	}

	// Attributes declared by the rule. Values of public attributes
	// are stored in the rule target, in the same order as the
	// attributes in the rule definition.
	publicAttrValues := ruleTarget.Message.PublicAttrValues
	for _, namedAttr := range ruleDefinition.Message.Attrs {
		attr := queryAttr[TReference]{name: namedAttr.Name}
		switch namedAttr.Attr.GetType().(type) {
		case *model_starlark_pb.Attr_Output, *model_starlark_pb.Attr_OutputList:
			attr.isOutput = true
		}

		if !strings.HasPrefix(namedAttr.Name, "_") {
			if len(publicAttrValues) == 0 {
				return nil, errors.New("rule target has fewer public attr values than the rule definition has public attrs")
			}
			valueParts := publicAttrValues[0].ValueParts
			publicAttrValues = publicAttrValues[1:]

			// Values that are None cause the default value
			// to be used.
			isNone := false
			if len(valueParts) == 1 && len(valueParts[0].Conditions) == 0 {
				if noMatch, ok := valueParts[0].NoMatch.(*model_starlark_pb.Select_Group_NoMatchValue); ok {
					_, isNone = noMatch.NoMatchValue.GetKind().(*model_starlark_pb.Value_None)
				}
			}
			if !isNone {
				attr.isExplicit = true
				for _, selectGroup := range valueParts {
					attr.appendSelectGroup(model_core.Nested(ruleTarget, selectGroup))
				}
			}
		}

		if !attr.isExplicit {
			defaultValue := namedAttr.Attr.GetDefault()
			if defaultValue == nil {
				// Mandatory attribute without a value.
				continue
			}
			attr.parts = [][]model_core.Message[*model_starlark_pb.Value, TReference]{{
				model_core.Nested(ruleDefinition, defaultValue),
			}}
		}
		t.attrs = append(t.attrs, attr)
	}
	if l := len(publicAttrValues); l != 0 {
		return nil, fmt.Errorf("rule target has %d more public attr values than the rule definition has public attrs", l)
	}
	return t, nil
}

// visitQueryAttrLabels calls a function for each label contained in
// all possible values of an attribute, and optionally the labels of
// the conditions of select() expressions.
func (c *baseComputer[TReference, TMetadata]) visitQueryAttrLabels(ctx context.Context, attr *queryAttr[TReference], includeConditions bool, visitor model_starlark.LabelVisitor) error {
	if includeConditions {
		for _, conditionLabel := range attr.conditionLabels {
			resolvedLabel, err := label.NewResolvedLabel(conditionLabel)
			if err != nil {
				return fmt.Errorf("invalid condition label %#v: %w", conditionLabel, err)
			}
			if err := visitor(resolvedLabel); err != nil {
				return err
			}
		}
	}
	for _, alternatives := range attr.parts {
		for _, alternative := range alternatives {
			if err := model_starlark.VisitAttrValueLabels(ctx, &c.valueReaders, alternative, visitor); err != nil {
				return err
			}
		}
	}
	return nil
}

// queryValueString is the string representation of a Starlark value,
// as matched by attr().
type queryValueString struct {
	isList   bool
	elements []string
	scalar   string
}

func (s *queryValueString) String() string {
	if s.isList {
		return "[" + strings.Join(s.elements, ", ") + "]"
	}
	return s.scalar
}

// stringifyQueryValue converts a Starlark value to a string, so that
// it can be matched by attr(). Lists are converted to "[a, b, c]",
// dicts are converted to "{a=b, c=d}", labels are converted to
// canonical labels, and Booleans are converted to "0" and "1". It
// returns false if the value has no string representation.
func (c *baseComputer[TReference, TMetadata]) stringifyQueryValue(ctx context.Context, value model_core.Message[*model_starlark_pb.Value, TReference]) (queryValueString, bool, error) {
	switch kind := value.Message.GetKind().(type) {
	case *model_starlark_pb.Value_Bool:
		if kind.Bool {
			return queryValueString{scalar: "1"}, true, nil
		}
		return queryValueString{scalar: "0"}, true, nil
	case *model_starlark_pb.Value_Int:
		return queryValueString{scalar: model_starlark.DecodeInt(kind.Int).String()}, true, nil
	case *model_starlark_pb.Value_Label:
		canonicalLabel, err := canonicalizeQueryLabel(kind.Label)
		if err != nil {
			return queryValueString{}, false, err
		}
		return queryValueString{scalar: canonicalLabel.String()}, true, nil
	case *model_starlark_pb.Value_None:
		return queryValueString{}, true, nil
	case *model_starlark_pb.Value_Str:
		return queryValueString{scalar: kind.Str}, true, nil
	case *model_starlark_pb.Value_List:
		s := queryValueString{isList: true}
		var errIter error
		for element := range model_starlark.AllListLeafElements(ctx, c.valueReaders.List, model_core.Nested(value, kind.List.Elements), &errIter) {
			elementString, ok, err := c.stringifyQueryValue(ctx, element)
			if err != nil || !ok {
				return queryValueString{}, ok, err
			}
			s.elements = append(s.elements, elementString.String())
		}
		return s, true, errIter
	case *model_starlark_pb.Value_Dict:
		var entries []string
		var errIter error
		for key, value := range model_starlark.AllDictLeafEntries(ctx, c.valueReaders.Dict, model_core.Nested(value, kind.Dict), &errIter) {
			keyString, ok, err := c.stringifyQueryValue(ctx, key)
			if err != nil || !ok {
				return queryValueString{}, ok, err
			}
			valueString, ok, err := c.stringifyQueryValue(ctx, value)
			if err != nil || !ok {
				return queryValueString{}, ok, err
			}
			entries = append(entries, keyString.String()+"="+valueString.String())
		}
		return queryValueString{scalar: "{" + strings.Join(entries, ", ") + "}"}, true, errIter
	default:
		return queryValueString{}, false, nil
	}
}

// maximumQueryAttrStrings limits the number of combinations of
// select() branches that attr() considers when matching attribute
// values. Attributes whose values consist of multiple select()
// expressions that are concatenated can have a number of possible
// values that is exponential in the number of select() expressions.
// Instead of silently ignoring some of these values, attr() fails if
// this limit is exceeded.
const maximumQueryAttrStrings = 1000

// stringifyQueryAttr returns string representations of all possible
// values of an attribute.
func (c *baseComputer[TReference, TMetadata]) stringifyQueryAttr(ctx context.Context, attr *queryAttr[TReference]) ([]string, error) {
	// Compute the cartesian product of the values of all parts,
	// concatenating them.
	combinations := []queryValueString{{}}
	for i, alternatives := range attr.parts {
		var newCombinations []queryValueString
		for _, alternative := range alternatives {
			alternativeString, ok, err := c.stringifyQueryValue(ctx, alternative)
			if err != nil {
				return nil, err
			}
			if !ok {
				continue
			}
			for _, combination := range combinations {
				if len(newCombinations) >= maximumQueryAttrStrings {
					return nil, fmt.Errorf("more than %d possible values exist, due to concatenated select() expressions", maximumQueryAttrStrings)
				}
				if i == 0 {
					newCombinations = append(newCombinations, alternativeString)
				} else if combination.isList && alternativeString.isList {
					newCombinations = append(newCombinations, queryValueString{
						isList:   true,
						elements: append(slices.Clip(combination.elements), alternativeString.elements...),
					})
				} else {
					newCombinations = append(newCombinations, queryValueString{
						scalar: combination.String() + alternativeString.String(),
					})
				}
			}
		}
		combinations = newCombinations
	}
	if len(attr.parts) == 0 {
		return nil, nil
	}
	attrStrings := make([]string, 0, len(combinations))
	for _, combination := range combinations {
		attrStrings = append(attrStrings, combination.String())
	}
	return attrStrings, nil
}

// parseRootModuleQuery parses a query expression that may contain
// apparent target patterns, as provided by clients. Apparent repo
// names are resolved from the perspective of the root module.
func parseRootModuleQuery[TReference any](e labelResolverEnvironment[TReference], query string) (label.Query[label.CanonicalTargetPattern], error) {
	apparentQuery, err := label.NewQuery(query, label.NewApparentTargetPattern)
	if err != nil {
		return label.Query[label.CanonicalTargetPattern]{}, fmt.Errorf("invalid query: %w", err)
	}
	resolver := newLabelResolver(e)
	rootModule, err := resolver.GetRootModule()
	if err != nil {
		return label.Query[label.CanonicalTargetPattern]{}, err
	}
	return label.CanonicalizeQuery(resolver, rootModule.ToModuleInstance(nil).GetBareCanonicalRepo(), apparentQuery)
}

// newQueryExpansionKey returns the QueryExpansion key that needs to
// be requested to evaluate a query expression.
func newQueryExpansionKey(query label.Query[label.CanonicalTargetPattern], includeImplicitDeps bool) *model_analysis_pb.QueryExpansion_Key {
	// Implicit dependencies don't affect the results of queries
	// that don't follow any dependencies (e.g., target patterns).
	// Don't request separate keys for them.
	return &model_analysis_pb.QueryExpansion_Key{
		Query:               label.QueryToString(query),
		IncludeImplicitDeps: includeImplicitDeps && queryUsesDependencies(query),
	}
}

// getQueryLabels returns the labels of the targets yielded by a query
// expression.
func (c *baseComputer[TReference, TMetadata]) getQueryLabels(ctx context.Context, e queryExpansionEnvironment[TReference], query label.Query[label.CanonicalTargetPattern], includeImplicitDeps bool) ([]label.CanonicalLabel, error) {
	value := e.GetQueryExpansionValue(newQueryExpansionKey(query, includeImplicitDeps))
	if !value.IsSet() {
		return nil, evaluation.ErrMissingDependency
	}
	var errIter error
	labels := slices.Collect(c.allTargetLabels(ctx, model_core.Nested(value, value.Message.TargetLabels), &errIter))
	if errIter != nil {
		return nil, errIter
	}
	return labels, nil
}

// getQueryLabelsOfOperands returns the labels of the targets yielded
// by operands of a query expression, identified by their index in the
// list of expressions of the query. All operands are requested before
// returning ErrMissingDependency, so that they can be evaluated
// concurrently.
func (c *baseComputer[TReference, TMetadata]) getQueryLabelsOfOperands(ctx context.Context, e queryExpansionEnvironment[TReference], query label.Query[label.CanonicalTargetPattern], includeImplicitDeps bool, operands ...int) ([][]label.CanonicalLabel, error) {
	results := make([][]label.CanonicalLabel, 0, len(operands))
	missingDependencies := false
	for _, operand := range operands {
		labels, err := c.getQueryLabels(ctx, e, query.GetSubquery(operand), includeImplicitDeps)
		if err != nil {
			if !errors.Is(err, evaluation.ErrMissingDependency) {
				return nil, err
			}
			missingDependencies = true
		}
		results = append(results, labels)
	}
	if missingDependencies {
		return nil, evaluation.ErrMissingDependency
	}
	return results, nil
}

type getQueryTargetDefinitionsEnvironment[TReference any] interface {
	GetTargetValue(*model_analysis_pb.Target_Key) model_core.Message[*model_analysis_pb.Target_Value, TReference]
}

// getQueryTargetDefinitions returns the definitions of a list of
// targets. This can also be used to check that targets exist.
func getQueryTargetDefinitions[TReference any](e getQueryTargetDefinitionsEnvironment[TReference], labels []label.CanonicalLabel) ([]model_core.Message[*model_starlark_pb.Target_Definition, TReference], error) {
	definitions := make([]model_core.Message[*model_starlark_pb.Target_Definition, TReference], 0, len(labels))
	missingDependencies := false
	for _, l := range labels {
		target := e.GetTargetValue(&model_analysis_pb.Target_Key{Label: l.String()})
		if !target.IsSet() {
			missingDependencies = true
			continue
		}
		definitions = append(definitions, model_core.Nested(target, target.Message.Definition))
	}
	if missingDependencies {
		return nil, evaluation.ErrMissingDependency
	}
	return definitions, nil
}

type getQueryDirectDependenciesEnvironment[TReference any] interface {
	GetTargetDirectDependenciesValue(*model_analysis_pb.TargetDirectDependencies_Key) model_core.Message[*model_analysis_pb.TargetDirectDependencies_Value, TReference]
}

// getQueryDirectDependencies returns the direct dependencies of a set
// of targets, as a map from the label of each target to the labels of
// its dependencies.
func (c *baseComputer[TReference, TMetadata]) getQueryDirectDependencies(ctx context.Context, e getQueryDirectDependenciesEnvironment[TReference], labels []label.CanonicalLabel, includeImplicitDeps bool) (map[label.CanonicalLabel][]label.CanonicalLabel, error) {
	dependencies := make(map[label.CanonicalLabel][]label.CanonicalLabel, len(labels))
	missingDependencies := false
	for _, l := range labels {
		value := e.GetTargetDirectDependenciesValue(&model_analysis_pb.TargetDirectDependencies_Key{
			Label:               l.String(),
			IncludeImplicitDeps: includeImplicitDeps,
		})
		if !value.IsSet() {
			missingDependencies = true
			continue
		}
		var errIter error
		dependencies[l] = slices.Collect(c.allTargetLabels(ctx, model_core.Nested(value, value.Message.TargetLabels), &errIter))
		if errIter != nil {
			return nil, fmt.Errorf("failed to obtain direct dependencies of target %#v: %w", l.String(), errIter)
		}
	}
	if missingDependencies {
		return nil, evaluation.ErrMissingDependency
	}
	return dependencies, nil
}

// queryDeps computes the transitive closure of the dependencies of a
// set of targets, optionally limiting the search depth.
func (c *baseComputer[TReference, TMetadata]) queryDeps(ctx context.Context, e getQueryDirectDependenciesEnvironment[TReference], labels []label.CanonicalLabel, maximumDepth *uint32, includeImplicitDeps bool) (labelSet, error) {
	// Perform a breadth-first search, requesting the dependencies
	// of all targets at the same depth at once.
	seen := newLabelSet(labels)
	frontier := labels
	for depth := uint32(0); len(frontier) > 0 && (maximumDepth == nil || depth < *maximumDepth); depth++ {
		dependencies, err := c.getQueryDirectDependencies(ctx, e, frontier, includeImplicitDeps)
		if err != nil {
			return nil, err
		}
		var newFrontier []label.CanonicalLabel
		for _, l := range frontier {
			for _, dependency := range dependencies[l] {
				if _, ok := seen[dependency]; !ok {
					seen[dependency] = struct{}{}
					newFrontier = append(newFrontier, dependency)
				}
			}
		}
		frontier = newFrontier
	}
	return seen, nil
}

// isQueryRuleTarget returns whether a target is matched by rules(),
// and by target patterns like "//foo:all". In addition to rule targets,
// this includes targets declared using built-in functions that behave
// like rules.
func isQueryRuleTarget(definition *model_starlark_pb.Target_Definition) bool {
	switch definition.GetKind().(type) {
	case *model_starlark_pb.Target_Definition_Alias,
		*model_starlark_pb.Target_Definition_LabelSetting,
		*model_starlark_pb.Target_Definition_RuleTarget:
		return true
	default:
		return false
	}
}

// getPerTargetQueryOperand returns the index of the operand of a query
// expression that processes targets individually, only yielding labels
// in the same package as the target (e.g., kind() or packages()). Such
// expressions can be evaluated for each package separately, as the
// result for any target does not depend on other targets.
//
// TODO: tests() is only part of this list because test_suite() is not
// yet supported, meaning that tests(x) merely yields the test targets
// contained in x. Once test_suite() is implemented as a built-in,
// tests() needs to expand test suites, which may refer to targets in
// other packages.
func getPerTargetQueryOperand(expression label.QueryExpression[label.CanonicalTargetPattern]) (int, bool) {
	switch e := expression.(type) {
	case *label.QueryFilter[label.CanonicalTargetPattern]:
		return e.Expression, true
	case *label.QueryKind[label.CanonicalTargetPattern]:
		return e.Expression, true
	case *label.QueryAttr[label.CanonicalTargetPattern]:
		return e.Expression, true
	case *label.QueryTag[label.CanonicalTargetPattern]:
		return e.Expression, true
	case *label.QueryPackages[label.CanonicalTargetPattern]:
		return e.Expression, true
	case *label.QueryTests[label.CanonicalTargetPattern]:
		return e.Expression, true
	case *label.QueryRules[label.CanonicalTargetPattern]:
		return e.Expression, true
	case *label.QueryExecutables[label.CanonicalTargetPattern]:
		return e.Expression, true
	default:
		return 0, false
	}
}

// applyPerTargetQueryExpression evaluates a query expression that
// processes targets individually, given the labels of the targets
// yielded by its operand.
func (c *baseComputer[TReference, TMetadata]) applyPerTargetQueryExpression(ctx context.Context, e QueryExpansionEnvironment[TReference, TMetadata], expression label.QueryExpression[label.CanonicalTargetPattern], labels []label.CanonicalLabel) (labelSet, error) {
	switch expression := expression.(type) {
	case *label.QueryFilter[label.CanonicalTargetPattern]:
		pattern, err := regexp.Compile(expression.Pattern)
		if err != nil {
			return nil, fmt.Errorf("invalid regular expression %#v: %w", expression.Pattern, err)
		}
		results := labelSet{}
		for _, l := range labels {
			if pattern.MatchString(l.String()) {
				results[l] = struct{}{}
			}
		}
		return results, nil

	case *label.QueryKind[label.CanonicalTargetPattern]:
		pattern, err := regexp.Compile(expression.Pattern)
		if err != nil {
			return nil, fmt.Errorf("invalid regular expression %#v: %w", expression.Pattern, err)
		}
		definitions, err := getQueryTargetDefinitions(e, labels)
		if err != nil {
			return nil, err
		}
		results := labelSet{}
		for i, definition := range definitions {
			targetKind, err := model_starlark.GetTargetKind(definition.Message)
			if err != nil {
				return nil, fmt.Errorf("failed to obtain kind of target %#v: %w", labels[i].String(), err)
			}
			if pattern.MatchString(targetKind) {
				results[labels[i]] = struct{}{}
			}
		}
		return results, nil

	case *label.QueryAttr[label.CanonicalTargetPattern]:
		pattern, err := regexp.Compile(expression.Pattern)
		if err != nil {
			return nil, fmt.Errorf("invalid regular expression %#v: %w", expression.Pattern, err)
		}
		results := labelSet{}
		if err := forEachQueryRuleTargetAttr(e, labels, expression.AttrName, func(l label.CanonicalLabel, attr *queryAttr[TReference]) error {
			attrStrings, err := c.stringifyQueryAttr(ctx, attr)
			if err != nil {
				return err
			}
			if slices.ContainsFunc(attrStrings, pattern.MatchString) {
				results[l] = struct{}{}
			}
			return nil
		}); err != nil {
			return nil, err
		}
		return results, nil

	case *label.QueryTag[label.CanonicalTargetPattern]:
		definitions, err := getQueryTargetDefinitions(e, labels)
		if err != nil {
			return nil, err
		}
		results := labelSet{}
		for i, definition := range definitions {
			// Tags of rule targets are sorted alphabetically.
			// Other kinds of targets don't have any tags.
			if ruleTarget, ok := definition.Message.GetKind().(*model_starlark_pb.Target_Definition_RuleTarget); ok {
				if _, found := slices.BinarySearch(ruleTarget.RuleTarget.Tags, expression.Tag); found {
					results[labels[i]] = struct{}{}
				}
			}
		}
		return results, nil

	case *label.QueryPackages[label.CanonicalTargetPattern]:
		results := labelSet{}
		for _, l := range labels {
			results[l.GetCanonicalPackage().AsCanonicalLabel()] = struct{}{}
		}
		return results, nil

	case *label.QueryRules[label.CanonicalTargetPattern]:
		definitions, err := getQueryTargetDefinitions(e, labels)
		if err != nil {
			return nil, err
		}
		results := labelSet{}
		for i, definition := range definitions {
			if isQueryRuleTarget(definition.Message) {
				results[labels[i]] = struct{}{}
			}
		}
		return results, nil

	case *label.QueryTests[label.CanonicalTargetPattern], *label.QueryExecutables[label.CanonicalTargetPattern]:
		// Both tests() and executables() select rule targets
		// based on the type of their rule definitions. Tests
		// are executable, but are only yielded by tests(), as
		// is the case for Bazel.
		wantType := model_starlark_pb.Rule_Definition_EXECUTABLE
		if _, ok := expression.(*label.QueryTests[label.CanonicalTargetPattern]); ok {
			wantType = model_starlark_pb.Rule_Definition_TEST
		}
		definitions, err := getQueryTargetDefinitions(e, labels)
		if err != nil {
			return nil, err
		}
		results := labelSet{}
		missingDependencies := false
		for i, definition := range definitions {
			ruleTarget, ok := definition.Message.GetKind().(*model_starlark_pb.Target_Definition_RuleTarget)
			if !ok {
				continue
			}
			ruleIdentifier, err := label.NewCanonicalStarlarkIdentifier(ruleTarget.RuleTarget.RuleIdentifier)
			if err != nil {
				return nil, fmt.Errorf("invalid rule identifier %#v: %w", ruleTarget.RuleTarget.RuleIdentifier, err)
			}
			ruleDefinition, err := getQueryRuleDefinition(e, ruleIdentifier)
			if err != nil {
				if errors.Is(err, evaluation.ErrMissingDependency) {
					missingDependencies = true
					continue
				}
				return nil, err
			}
			if ruleDefinition.Message.Type == wantType {
				results[labels[i]] = struct{}{}
			}
		}
		if missingDependencies {
			return nil, evaluation.ErrMissingDependency
		}
		return results, nil

	default:
		return nil, errors.New("query expression does not process targets individually")
	}
}

// combineQuerySetOperation applies a set operation to the results of
// its operands. The left operand is modified in place.
func combineQuerySetOperation(operator label.QuerySetOperator, left, right labelSet) (labelSet, error) {
	switch operator {
	case label.QuerySetOperatorUnion:
		maps.Copy(left, right)
	case label.QuerySetOperatorIntersect:
		maps.DeleteFunc(left, func(l label.CanonicalLabel, _ struct{}) bool {
			_, ok := right[l]
			return !ok
		})
	case label.QuerySetOperatorExcept:
		maps.DeleteFunc(left, func(l label.CanonicalLabel, _ struct{}) bool {
			_, ok := right[l]
			return ok
		})
	default:
		return nil, errors.New("unknown set operator")
	}
	return left, nil
}

// queryUsesDependencies returns whether a query contains functions that
// follow dependencies between targets. If not, whether implicit
// dependencies are included does not affect the results of the query.
func queryUsesDependencies(query label.Query[label.CanonicalTargetPattern]) bool {
	for _, expression := range query.GetExpressions() {
		switch expression.(type) {
		case *label.QueryDeps[label.CanonicalTargetPattern],
			*label.QueryReverseDeps[label.CanonicalTargetPattern],
			*label.QuerySomePath[label.CanonicalTargetPattern],
			*label.QueryAllPaths[label.CanonicalTargetPattern],
			*label.QuerySamePackageDirectReverseDeps[label.CanonicalTargetPattern]:
			return true
		}
	}
	return false
}

// getQuerySiblingsPackages returns the packages whose targets are
// yielded by siblings(), if the operand of siblings() is a set of
// target patterns of shape "//foo:*" or "//foo:all-targets". This
// permits evaluating siblings() without expanding these target
// patterns.
//
// This is valid even if packages contain targets named "*" or
// "all-targets", which these target patterns would match exclusively,
// as these targets have the same siblings. This is not the case for
// target patterns of shape "//foo:all", as these yield no targets for
// packages that only contain file targets.
func getQuerySiblingsPackages(query label.Query[label.CanonicalTargetPattern], siblings *label.QuerySiblings[label.CanonicalTargetPattern]) ([]label.CanonicalPackage, bool) {
	set, ok := query.GetExpressions()[siblings.Expression].(*label.QuerySet[label.CanonicalTargetPattern])
	if !ok {
		return nil, false
	}
	packages := make([]label.CanonicalPackage, 0, len(set.TargetPatterns))
	for _, targetPattern := range set.TargetPatterns {
		initialTarget, includeFileTargets, ok := targetPattern.AsSinglePackageTargetPattern()
		if !ok || !includeFileTargets {
			return nil, false
		}
		packages = append(packages, initialTarget.GetCanonicalPackage())
	}
	return packages, true
}

// getQueryPackageTargets returns the labels of all targets in a
// package, including file targets, as yielded by siblings(). In
// addition to that, it returns the labels of the targets that are
// matched by rules(). These can be computed without loading the targets
// individually, as their definitions are contained in the package.
func (c *baseComputer[TReference, TMetadata]) getQueryPackageTargets(ctx context.Context, e QueryExpansionEnvironment[TReference, TMetadata], canonicalPackage label.CanonicalPackage) (labelSet, labelSet, error) {
	packageValue := e.GetPackageValue(&model_analysis_pb.Package_Key{
		Label: canonicalPackage.String(),
	})
	if !packageValue.IsSet() {
		return nil, nil, evaluation.ErrMissingDependency
	}
	allTargets, ruleTargets := labelSet{}, labelSet{}
	for _, entry := range []struct {
		includeFileTargets bool
		results            labelSet
	}{
		{true, allTargets},
		{false, ruleTargets},
	} {
		if err := c.forEachPackageTargetLabel(ctx, canonicalPackage, packageValue, entry.includeFileTargets, func(l label.CanonicalLabel) error {
			entry.results[l] = struct{}{}
			return nil
		}); err != nil {
			return nil, nil, err
		}
	}
	return allTargets, ruleTargets, nil
}

// getQueryPredicatePackages returns the packages of the targets
// yielded by the predicate of visible(), by requesting the results of
// packages() applied to the predicate.
func (c *baseComputer[TReference, TMetadata]) getQueryPredicatePackages(ctx context.Context, e QueryExpansionEnvironment[TReference, TMetadata], predicate label.Query[label.CanonicalTargetPattern], includeImplicitDeps bool) ([]label.CanonicalPackage, error) {
	queryExpansion := e.GetQueryExpansionValue(newQueryExpansionKey(label.NewPackagesQuery(predicate), includeImplicitDeps))
	if !queryExpansion.IsSet() {
		return nil, evaluation.ErrMissingDependency
	}
	var packages []label.CanonicalPackage
	var errIter error
	for l := range c.allTargetLabels(ctx, model_core.Nested(queryExpansion, queryExpansion.Message.TargetLabels), &errIter) {
		packages = append(packages, l.GetCanonicalPackage())
	}
	if errIter != nil {
		return nil, errIter
	}
	return packages, nil
}

// applyQueryVisible returns the targets in a list of targets that are
// visible to all of the provided packages, as done by visible(). Targets
// are always visible to the package containing them.
func (c *baseComputer[TReference, TMetadata]) applyQueryVisible(ctx context.Context, e QueryExpansionEnvironment[TReference, TMetadata], predicatePackages []label.CanonicalPackage, labels []label.CanonicalLabel) (labelSet, error) {
	definitions, err := getQueryTargetDefinitions(e, labels)
	if err != nil {
		return nil, err
	}
	results := labelSet{}
	missingDependencies := false
	for i, definition := range definitions {
		l := labels[i]
		visibility, restricted, err := getTargetVisibility(e, l, definition)
		if err != nil {
			if !errors.Is(err, evaluation.ErrMissingDependency) {
				return nil, fmt.Errorf("failed to obtain visibility of target %#v: %w", l.String(), err)
			}
			missingDependencies = true
			continue
		}
		isVisible := true
		if restricted {
			for _, predicatePackage := range predicatePackages {
				if predicatePackage == l.GetCanonicalPackage() {
					continue
				}
				contains, err := c.packageGroupContains(ctx, e, visibility, predicatePackage)
				if err != nil {
					if !errors.Is(err, evaluation.ErrMissingDependency) {
						return nil, fmt.Errorf("failed to determine whether target %#v is visible from package %#v: %w", l.String(), predicatePackage.String(), err)
					}
					missingDependencies = true
					isVisible = false
					break
				}
				if !contains {
					isVisible = false
					break
				}
			}
		}
		if isVisible {
			results[l] = struct{}{}
		}
	}
	if missingDependencies {
		return nil, evaluation.ErrMissingDependency
	}
	return results, nil
}

// isStreamingQueryExpression returns whether an expression can be
// evaluated by expandQueryStreaming().
func isStreamingQueryExpression(expression label.QueryExpression[label.CanonicalTargetPattern]) bool {
	switch expression.(type) {
	case *label.QuerySome[label.CanonicalTargetPattern], *label.QuerySiblings[label.CanonicalTargetPattern], *label.QueryVisible[label.CanonicalTargetPattern]:
		return true
	default:
		_, ok := getPerTargetQueryOperand(expression)
		return ok
	}
}

// queryStreamingBatchSize is the number of labels that
// expandQueryStreaming() passes to expressions that process targets
// individually at once.
const queryStreamingBatchSize = 1000

// expandQueryStreaming evaluates the top-level expression of a query
// by iterating over the results of its operand, without loading them
// into memory. This is possible for expressions whose results are
// sorted if the results of their operands are sorted, such as
// expressions that process targets individually, some(), siblings()
// and visible().
func (c *baseComputer[TReference, TMetadata]) expandQueryStreaming(ctx context.Context, e QueryExpansionEnvironment[TReference, TMetadata], query label.Query[label.CanonicalTargetPattern], includeImplicitDeps bool) (model_core.PatchedMessage[[]*model_analysis_pb.TargetLabel, TMetadata], error) {
	expressions := query.GetExpressions()
	expression := expressions[len(expressions)-1]

	treeBuilder := c.newTargetLabelTreeBuilder(ctx, e)
	defer treeBuilder.Discard()
	var lastLabel *label.CanonicalLabel
	pushLabel := func(l label.CanonicalLabel) error {
		if lastLabel != nil && l.Compare(*lastLabel) <= 0 {
			return fmt.Errorf("label %#v is not sorted after %#v", l.String(), lastLabel.String())
		}
		lastLabel = &l
		return pushTargetLabel(treeBuilder, l)
	}

	// siblings() whose operand consists of target patterns
	// matching entire packages can be evaluated without expanding
	// the operand.
	if siblings, ok := expression.(*label.QuerySiblings[label.CanonicalTargetPattern]); ok {
		if packages, ok := getQuerySiblingsPackages(query, siblings); ok {
			slices.SortFunc(packages, func(a, b label.CanonicalPackage) int {
				return a.AsCanonicalLabel().Compare(b.AsCanonicalLabel())
			})
			missingDependencies := false
			for _, canonicalPackage := range slices.Compact(packages) {
				if err := c.pushQueryPackageTargets(ctx, e, canonicalPackage, pushLabel); err != nil {
					if !errors.Is(err, evaluation.ErrMissingDependency) {
						return model_core.PatchedMessage[[]*model_analysis_pb.TargetLabel, TMetadata]{}, err
					}
					missingDependencies = true
				}
			}
			if missingDependencies {
				return model_core.PatchedMessage[[]*model_analysis_pb.TargetLabel, TMetadata]{}, evaluation.ErrMissingDependency
			}
			return treeBuilder.FinalizeList()
		}
	}

	var operand int
	applyToBatch := func(batch []label.CanonicalLabel) (labelSet, error) {
		return c.applyPerTargetQueryExpression(ctx, e, expression, batch)
	}
	missingDependencies := false
	switch expr := expression.(type) {
	case *label.QuerySome[label.CanonicalTargetPattern]:
		operand = expr.Expression
	case *label.QuerySiblings[label.CanonicalTargetPattern]:
		operand = expr.Expression
	case *label.QueryVisible[label.CanonicalTargetPattern]:
		// Visibility is determined at the package level,
		// meaning that only the packages of the targets in
		// the predicate are needed. Request these through a
		// separate key, so that they don't need to be computed
		// for each batch.
		operand = expr.Expression
		predicatePackages, err := c.getQueryPredicatePackages(ctx, e, query.GetSubquery(expr.Predicate), includeImplicitDeps)
		if err != nil {
			if !errors.Is(err, evaluation.ErrMissingDependency) {
				return model_core.PatchedMessage[[]*model_analysis_pb.TargetLabel, TMetadata]{}, err
			}
			// Still request the operand, so that it can
			// be evaluated concurrently.
			missingDependencies = true
		}
		applyToBatch = func(batch []label.CanonicalLabel) (labelSet, error) {
			return c.applyQueryVisible(ctx, e, predicatePackages, batch)
		}
	default:
		operand, _ = getPerTargetQueryOperand(expression)
	}
	queryExpansion := e.GetQueryExpansionValue(newQueryExpansionKey(query.GetSubquery(operand), includeImplicitDeps))
	if missingDependencies || !queryExpansion.IsSet() {
		return model_core.PatchedMessage[[]*model_analysis_pb.TargetLabel, TMetadata]{}, evaluation.ErrMissingDependency
	}
	var errIter error
	labels := c.allTargetLabels(ctx, model_core.Nested(queryExpansion, queryExpansion.Message.TargetLabels), &errIter)

	switch expr := expression.(type) {
	case *label.QuerySome[label.CanonicalTargetPattern]:
		if expr.Count == 0 {
			return model_core.PatchedMessage[[]*model_analysis_pb.TargetLabel, TMetadata]{}, errors.New("count of some() must be positive")
		}
		count := uint32(0)
		for l := range labels {
			if err := pushLabel(l); err != nil {
				return model_core.PatchedMessage[[]*model_analysis_pb.TargetLabel, TMetadata]{}, err
			}
			count++
			if count >= expr.Count {
				break
			}
		}
		if errIter != nil {
			return model_core.PatchedMessage[[]*model_analysis_pb.TargetLabel, TMetadata]{}, errIter
		}
		if count == 0 {
			return model_core.PatchedMessage[[]*model_analysis_pb.TargetLabel, TMetadata]{}, errors.New("argument set of some() is empty")
		}

	case *label.QuerySiblings[label.CanonicalTargetPattern]:
		// Labels belonging to the same package are adjacent,
		// and packages are sorted in the same order as their
		// targets. This means that the targets of each package
		// can be added as soon as it is encountered.
		var lastPackage *label.CanonicalPackage
		for l := range labels {
			canonicalPackage := l.GetCanonicalPackage()
			if lastPackage != nil && *lastPackage == canonicalPackage {
				continue
			}
			lastPackage = &canonicalPackage
			if err := c.pushQueryPackageTargets(ctx, e, canonicalPackage, pushLabel); err != nil {
				if !errors.Is(err, evaluation.ErrMissingDependency) {
					return model_core.PatchedMessage[[]*model_analysis_pb.TargetLabel, TMetadata]{}, err
				}
				missingDependencies = true
			}
		}
		if errIter != nil {
			return model_core.PatchedMessage[[]*model_analysis_pb.TargetLabel, TMetadata]{}, errIter
		}

	default:
		// Expressions that process targets individually,
		// including visible(), are applied to batches of
		// labels. Their results are sorted and follow the
		// results of previous batches, though packages() may
		// yield the same package for adjacent batches.
		batch := make([]label.CanonicalLabel, 0, queryStreamingBatchSize)
		flushBatch := func() error {
			results, err := applyToBatch(batch)
			batch = batch[:0]
			if err != nil {
				if !errors.Is(err, evaluation.ErrMissingDependency) {
					return err
				}
				// Continue processing other batches,
				// so that all dependencies are
				// requested.
				missingDependencies = true
				return nil
			}
			for _, l := range results.sorted() {
				if lastLabel == nil || *lastLabel != l {
					if err := pushLabel(l); err != nil {
						return err
					}
				}
			}
			return nil
		}
		for l := range labels {
			batch = append(batch, l)
			if len(batch) == queryStreamingBatchSize {
				if err := flushBatch(); err != nil {
					return model_core.PatchedMessage[[]*model_analysis_pb.TargetLabel, TMetadata]{}, err
				}
			}
		}
		if errIter != nil {
			return model_core.PatchedMessage[[]*model_analysis_pb.TargetLabel, TMetadata]{}, errIter
		}
		if len(batch) > 0 {
			if err := flushBatch(); err != nil {
				return model_core.PatchedMessage[[]*model_analysis_pb.TargetLabel, TMetadata]{}, err
			}
		}
	}
	if missingDependencies {
		return model_core.PatchedMessage[[]*model_analysis_pb.TargetLabel, TMetadata]{}, evaluation.ErrMissingDependency
	}
	return treeBuilder.FinalizeList()
}

// pushQueryPackageTargets calls a function for the labels of all
// targets in a package, including file targets, in sorted order.
func (c *baseComputer[TReference, TMetadata]) pushQueryPackageTargets(ctx context.Context, e QueryExpansionEnvironment[TReference, TMetadata], canonicalPackage label.CanonicalPackage, yield func(label.CanonicalLabel) error) error {
	packageValue := e.GetPackageValue(&model_analysis_pb.Package_Key{
		Label: canonicalPackage.String(),
	})
	if !packageValue.IsSet() {
		return evaluation.ErrMissingDependency
	}
	return c.forEachPackageTargetLabel(ctx, canonicalPackage, packageValue, true, yield)
}

// evaluateQuery evaluates the top-level expression of a query. Its
// operands are evaluated by requesting separate QueryExpansion keys.
// This function is only used for expressions whose results can't be
// computed without loading them into memory (e.g., deps()). Other
// expressions are evaluated by expandQuerySet(),
// expandQuerySetOperation() and expandQueryStreaming().
func (c *baseComputer[TReference, TMetadata]) evaluateQuery(ctx context.Context, e QueryExpansionEnvironment[TReference, TMetadata], query label.Query[label.CanonicalTargetPattern], includeImplicitDeps bool) (labelSet, error) {
	expressions := query.GetExpressions()
	getOperand := func(operand int) ([]label.CanonicalLabel, error) {
		return c.getQueryLabels(ctx, e, query.GetSubquery(operand), includeImplicitDeps)
	}
	switch expression := expressions[len(expressions)-1].(type) {
	case *label.QueryDeps[label.CanonicalTargetPattern]:
		labels, err := getOperand(expression.Expression)
		if err != nil {
			return nil, err
		}
		return c.queryDeps(ctx, e, labels, expression.MaximumDepth, includeImplicitDeps)

	case *label.QueryReverseDeps[label.CanonicalTargetPattern]:
		// Compute the transitive closure of the universe, and
		// invert the dependency graph within it.
		operands, err := c.getQueryLabelsOfOperands(ctx, e, query, includeImplicitDeps, expression.Universe, expression.Expression)
		if err != nil {
			return nil, err
		}
		universeSet, err := c.queryDeps(ctx, e, operands[0], nil, includeImplicitDeps)
		if err != nil {
			return nil, err
		}
		universe := universeSet.sorted()
		dependencies, err := c.getQueryDirectDependencies(ctx, e, universe, includeImplicitDeps)
		if err != nil {
			return nil, err
		}
		reverseDependencies := map[label.CanonicalLabel][]label.CanonicalLabel{}
		for _, l := range universe {
			for _, dependency := range dependencies[l] {
				reverseDependencies[dependency] = append(reverseDependencies[dependency], l)
			}
		}

		seen := labelSet{}
		var frontier []label.CanonicalLabel
		for _, l := range operands[1] {
			if _, ok := universeSet[l]; ok {
				seen[l] = struct{}{}
				frontier = append(frontier, l)
			}
		}
		maximumDepth := expression.MaximumDepth
		for depth := uint32(0); len(frontier) > 0 && (maximumDepth == nil || depth < *maximumDepth); depth++ {
			var newFrontier []label.CanonicalLabel
			for _, l := range frontier {
				for _, reverseDependency := range reverseDependencies[l] {
					if _, ok := seen[reverseDependency]; !ok {
						seen[reverseDependency] = struct{}{}
						newFrontier = append(newFrontier, reverseDependency)
					}
				}
			}
			frontier = newFrontier
		}
		return seen, nil

	case *label.QueryLabels[label.CanonicalTargetPattern]:
		labels, err := getOperand(expression.Expression)
		if err != nil {
			return nil, err
		}
		results := labelSet{}
		if err := forEachQueryRuleTargetAttr(e, labels, expression.AttrName, func(l label.CanonicalLabel, attr *queryAttr[TReference]) error {
			return c.visitQueryAttrLabels(ctx, attr, false, func(attrLabel label.ResolvedLabel) error {
				canonicalLabel, err := canonicalizeResolvedQueryLabel(attrLabel)
				if err != nil {
					return err
				}
				results[canonicalLabel] = struct{}{}
				return nil
			})
		}); err != nil {
			return nil, err
		}
		return results, nil

	case *label.QuerySomePath[label.CanonicalTargetPattern]:
		return nil, errors.New("somepath() is not supported yet")
	case *label.QueryAllPaths[label.CanonicalTargetPattern]:
		return nil, errors.New("allpaths() is not supported yet")
	case *label.QuerySamePackageDirectReverseDeps[label.CanonicalTargetPattern]:
		return nil, errors.New("same_pkg_direct_rdeps() is not supported yet")
	case *label.QueryBuildFiles[label.CanonicalTargetPattern]:
		return nil, errors.New("buildfiles() is not supported yet")
	case *label.QueryLoadFiles[label.CanonicalTargetPattern]:
		return nil, errors.New("loadfiles() is not supported yet")
	default:
		return nil, errors.New("unknown query expression type")
	}
}

