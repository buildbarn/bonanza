package analysis

import (
	"testing"

	"bonanza.build/pkg/label"
	model_core "bonanza.build/pkg/model/core"
	model_starlark "bonanza.build/pkg/model/starlark"
	model_analysis_pb "bonanza.build/pkg/proto/model/analysis"
	model_starlark_pb "bonanza.build/pkg/proto/model/starlark"
	"bonanza.build/pkg/storage/object"

	"github.com/buildbarn/bb-storage/pkg/util"
	"github.com/stretchr/testify/require"
)

func TestTargetOutputRegistrarRegisterOutput(t *testing.T) {
	newRegistrar := func() *targetOutputRegistrar[object.LocalReference, model_core.ReferenceMetadata] {
		return &targetOutputRegistrar[object.LocalReference, model_core.ReferenceMetadata]{
			variant:     model_core.NewSimpleMessage[object.LocalReference](&model_starlark_pb.TargetVariant{}),
			targetLabel: util.Must(label.NewCanonicalLabel("@@foo+//bar:baz")),

			outputsByPackageRelativePath: map[string]*targetOutput[model_core.ReferenceMetadata]{},
			outputsByFile:                map[*model_starlark.File[object.LocalReference, model_core.ReferenceMetadata]]*targetOutput[model_core.ReferenceMetadata]{},
		}
	}
	filename := util.Must(label.NewTargetName("out.txt"))

	t.Run("SameTypeTwice", func(t *testing.T) {
		// Like Bazel, declaring the same output twice should
		// yield the same file.
		or := newRegistrar()
		f1, err := or.registerOutput(filename, nil, model_starlark_pb.File_Owner_FILE)
		require.NoError(t, err)
		f2, err := or.registerOutput(filename, nil, model_starlark_pb.File_Owner_FILE)
		require.NoError(t, err)
		require.Same(t, f1, f2)
		require.Len(t, or.outputsByPackageRelativePath, 1)
		require.Len(t, or.outputsByFile, 1)

		// As both declarations refer to the same output, it
		// may only be generated by a single action.
		o := or.outputsByFile[f1.(*model_starlark.File[object.LocalReference, model_core.ReferenceMetadata])]
		definition := model_core.NewSimplePatchedMessage[model_core.ReferenceMetadata](&model_analysis_pb.TargetOutputDefinition{})
		require.NoError(t, o.setDefinition(definition))
		require.EqualError(t, o.setDefinition(definition), "file \"out.txt\" is an output of multiple actions")
	})

	t.Run("DifferentTypes", func(t *testing.T) {
		or := newRegistrar()
		_, err := or.registerOutput(filename, nil, model_starlark_pb.File_Owner_FILE)
		require.NoError(t, err)
		_, err = or.registerOutput(filename, nil, model_starlark_pb.File_Owner_DIRECTORY)
		require.EqualError(t, err, "file \"out.txt\" has already been declared as a regular file, not a directory")
		_, err = or.registerOutput(filename, nil, model_starlark_pb.File_Owner_SYMLINK)
		require.EqualError(t, err, "file \"out.txt\" has already been declared as a regular file, not a symbolic link")
	})

	t.Run("DifferentNames", func(t *testing.T) {
		or := newRegistrar()
		f1, err := or.registerOutput(filename, nil, model_starlark_pb.File_Owner_FILE)
		require.NoError(t, err)
		f2, err := or.registerOutput(util.Must(label.NewTargetName("other.txt")), nil, model_starlark_pb.File_Owner_FILE)
		require.NoError(t, err)
		require.NotSame(t, f1, f2)
		require.Len(t, or.outputsByPackageRelativePath, 2)
	})
}
